-- Call-In schema (Postgres). Applied by `npm run db:setup` (Supabase) and
-- automatically by the local PGlite dev database.
--
-- Timestamps are ISO-8601 UTC strings (text) so they compare and sort lexically,
-- matching how the app reads and writes them.

CREATE OR REPLACE FUNCTION iso_now() RETURNS text LANGUAGE sql STABLE AS $$
  SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$;

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('admin','caller','signin')),
  active integer NOT NULL DEFAULT 1,
  created_at text NOT NULL DEFAULT iso_now()
);

CREATE TABLE IF NOT EXISTS sessions (
  token text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS contacts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name text NOT NULL,
  last_name text NOT NULL,
  phone text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  street text NOT NULL DEFAULT '',
  city text NOT NULL DEFAULT '',
  state text NOT NULL DEFAULT '',
  zip text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  source text NOT NULL DEFAULT 'manual' CHECK (source IN ('import','walk_in','manual')),
  created_at text NOT NULL DEFAULT iso_now(),
  updated_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS contacts_phone ON contacts(phone) WHERE phone <> '';
CREATE INDEX IF NOT EXISTS contacts_email ON contacts(email) WHERE email <> '';
CREATE INDEX IF NOT EXISTS contacts_name ON contacts(lower(last_name), lower(first_name));

CREATE TABLE IF NOT EXISTS categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  series_id text,
  name text NOT NULL,
  tagline text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT '',
  tags text NOT NULL DEFAULT '[]',
  language text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'draft',
  status_reason text NOT NULL DEFAULT '',
  start_at text NOT NULL,
  end_at text,
  time_zone text NOT NULL,
  doors_at text,
  recurrence text NOT NULL DEFAULT 'none',
  rsvp_deadline text,
  location_type text NOT NULL DEFAULT 'in_person',
  venue_name text NOT NULL DEFAULT '',
  street text NOT NULL DEFAULT '',
  city text NOT NULL DEFAULT '',
  state text NOT NULL DEFAULT '',
  zip text NOT NULL DEFAULT '',
  room text NOT NULL DEFAULT '',
  online_url text NOT NULL DEFAULT '',
  online_meeting_id text NOT NULL DEFAULT '',
  online_passcode text NOT NULL DEFAULT '',
  parking_info text NOT NULL DEFAULT '',
  directions text NOT NULL DEFAULT '',
  accessibility text NOT NULL DEFAULT '',
  hosts text NOT NULL DEFAULT '[]',
  cohosts text NOT NULL DEFAULT '[]',
  contact_name text NOT NULL DEFAULT '',
  contact_phone text NOT NULL DEFAULT '',
  contact_email text NOT NULL DEFAULT '',
  speakers text NOT NULL DEFAULT '[]',
  sponsors text NOT NULL DEFAULT '[]',
  capacity integer,
  admission text NOT NULL DEFAULT 'free',
  price_tiers text NOT NULL DEFAULT '[]',
  ticket_url text NOT NULL DEFAULT '',
  age_restriction text NOT NULL DEFAULT 'all',
  dress_code text NOT NULL DEFAULT '',
  what_to_bring text NOT NULL DEFAULT '',
  food_drinks text NOT NULL DEFAULT '',
  plus_ones_allowed integer NOT NULL DEFAULT 0,
  max_guests integer NOT NULL DEFAULT 0,
  visibility text NOT NULL DEFAULT 'internal',
  agenda text NOT NULL DEFAULT '[]',
  cover_image text NOT NULL DEFAULT '',
  cover_thumb text NOT NULL DEFAULT '',
  flyer text NOT NULL DEFAULT '',
  venue_photos text NOT NULL DEFAULT '[]',
  gallery text NOT NULL DEFAULT '[]',
  attachments text NOT NULL DEFAULT '[]',
  website_url text NOT NULL DEFAULT '',
  facebook_url text NOT NULL DEFAULT '',
  social_links text NOT NULL DEFAULT '[]',
  caller_script text NOT NULL DEFAULT '',
  signin_instructions text NOT NULL DEFAULT '',
  internal_notes text NOT NULL DEFAULT '',
  archived_at text,
  created_by integer REFERENCES users(id),
  created_at text NOT NULL DEFAULT iso_now(),
  updated_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS events_start ON events(start_at);

CREATE TABLE IF NOT EXISTS event_staff (
  event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('caller','signin')),
  PRIMARY KEY (event_id, user_id, role)
);

CREATE TABLE IF NOT EXISTS registrations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  contact_id integer NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  rsvp text NOT NULL DEFAULT 'no_data',
  attendance text NOT NULL DEFAULT 'pending',
  guests integer NOT NULL DEFAULT 0,
  walk_in integer NOT NULL DEFAULT 0,
  last_called_at text,
  called_by integer REFERENCES users(id),
  checked_in_at text,
  created_at text NOT NULL DEFAULT iso_now(),
  UNIQUE (event_id, contact_id)
);
CREATE INDEX IF NOT EXISTS registrations_contact ON registrations(contact_id);

CREATE TABLE IF NOT EXISTS call_notes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_id integer NOT NULL REFERENCES registrations(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id),
  body text NOT NULL,
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS call_notes_reg ON call_notes(registration_id);

-- One row per call a caller logs; repeat touches within 15 minutes fold into one.
CREATE TABLE IF NOT EXISTS call_logs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_id integer NOT NULL REFERENCES registrations(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id),
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS call_logs_reg ON call_logs(registration_id);

-- Audit trail for every RSVP / attendance change.
CREATE TABLE IF NOT EXISTS status_changes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_id integer NOT NULL REFERENCES registrations(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('rsvp','attendance')),
  from_value text,
  to_value text,
  user_id integer NOT NULL REFERENCES users(id),
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS status_changes_reg ON status_changes(registration_id);

