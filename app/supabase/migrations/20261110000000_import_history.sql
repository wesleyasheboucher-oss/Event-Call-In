-- Import history: one row per contacts import, and one per file row saying what happened
-- to it. Updates keep each changed field's old and new value so they can be reviewed and undone.

CREATE TABLE IF NOT EXISTS imports (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  file_name text NOT NULL DEFAULT '',
  mode text NOT NULL DEFAULT 'skip' CHECK (mode IN ('skip','update')),
  tag_name text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT iso_now()
);

CREATE TABLE IF NOT EXISTS import_changes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  import_id integer NOT NULL REFERENCES imports(id) ON DELETE CASCADE,
  -- 'skipped' matched an existing contact and left it alone; 'in_file' repeated an earlier row.
  action text NOT NULL CHECK (action IN ('added','updated','skipped','in_file','error')),
  row_number integer NOT NULL DEFAULT 0,
  name text NOT NULL DEFAULT '',
  contact_id integer REFERENCES contacts(id) ON DELETE SET NULL,
  -- JSON: { field: [old, new] } for 'updated'
  changes text NOT NULL DEFAULT '{}',
  reason text NOT NULL DEFAULT '',
  undone_at text
);
CREATE INDEX IF NOT EXISTS import_changes_import ON import_changes(import_id);
CREATE INDEX IF NOT EXISTS import_changes_contact ON import_changes(contact_id) WHERE contact_id IS NOT NULL;

ALTER TABLE imports ENABLE ROW LEVEL SECURITY;
ALTER TABLE import_changes ENABLE ROW LEVEL SECURITY;
