-- Duplicate contacts check: pairs someone said are different people (so they stop being
-- suggested), and a snapshot of every contact merged into another (so nothing is lost).

CREATE TABLE IF NOT EXISTS contact_not_duplicates (
  a_id integer NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  b_id integer NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT iso_now(),
  PRIMARY KEY (a_id, b_id),
  CHECK (a_id < b_id)
);

CREATE TABLE IF NOT EXISTS contact_merges (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kept_id integer REFERENCES contacts(id) ON DELETE SET NULL,
  merged_id integer NOT NULL,
  -- JSON: the merged contact's row as it was, and what was written onto the kept contact
  snapshot text NOT NULL DEFAULT '{}',
  changes text NOT NULL DEFAULT '{}',
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS contact_merges_kept ON contact_merges(kept_id);

ALTER TABLE contact_not_duplicates ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_merges ENABLE ROW LEVEL SECURITY;
