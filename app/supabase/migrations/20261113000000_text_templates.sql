-- Text templates: ready-made messages callers send from their own phone ("share via text").
-- event_id ties a template to one event; null = usable for any event.

CREATE TABLE IF NOT EXISTS text_templates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  body text NOT NULL,
  event_id integer REFERENCES events(id) ON DELETE CASCADE,
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT iso_now(),
  updated_at text NOT NULL DEFAULT iso_now()
);
CREATE INDEX IF NOT EXISTS text_templates_event ON text_templates(event_id) WHERE event_id IS NOT NULL;

ALTER TABLE text_templates ENABLE ROW LEVEL SECURITY;
