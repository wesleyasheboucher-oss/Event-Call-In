-- Free-form tags on contacts (e.g. "Volunteer", "VIP", "Spanish speaker").

CREATE TABLE IF NOT EXISTS tags (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  color text NOT NULL DEFAULT 'slate',
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT iso_now()
);
-- Tag names are unique regardless of case ("vip" and "VIP" are the same tag).
CREATE UNIQUE INDEX IF NOT EXISTS tags_name_lower ON tags(lower(name));

CREATE TABLE IF NOT EXISTS contact_tags (
  contact_id integer NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
  tag_id integer NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
  added_by integer REFERENCES users(id) ON DELETE SET NULL,
  added_at text NOT NULL DEFAULT iso_now(),
  PRIMARY KEY (contact_id, tag_id)
);
CREATE INDEX IF NOT EXISTS contact_tags_tag ON contact_tags(tag_id);

ALTER TABLE tags ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_tags ENABLE ROW LEVEL SECURITY;
